bool gp100_usb_audio_gain_for_db(int16_t gain_db, float *gain)
{
    if (gain == NULL ||
        gain_db < GP100_USB_AUDIO_GAIN_MIN_DB ||
        gain_db > GP100_USB_AUDIO_GAIN_MAX_DB) {
        return false;
    }
    *gain = usb_audio_gain[
        (size_t)(gain_db - GP100_USB_AUDIO_GAIN_MIN_DB)];
    return true;
}
