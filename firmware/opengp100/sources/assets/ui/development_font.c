static gp100_bitmap_glyph_t glyphs[ASCII_GLYPH_COUNT];
static gp100_bitmap_font_t font = {
    glyphs, ASCII_GLYPH_COUNT, 8u, 6u
};
static bool initialized;

static const uint8_t *find_pattern(uint8_t character)
{
    size_t index;

    for (index = 0u; index < sizeof(patterns) / sizeof(patterns[0]); ++index) {
        if (patterns[index].character == character) {
            return patterns[index].rows;
        }
    }
    return NULL;
}

const gp100_bitmap_font_t *gp100_development_font_5x7(void)
{
    size_t index;

    if (!initialized) {
        for (index = 0u; index < ASCII_GLYPH_COUNT; ++index) {
            gp100_bitmap_glyph_t *glyph = &glyphs[index];
            uint8_t character = (uint8_t)(FIRST_ASCII + index);

            glyph->codepoint = character;
            glyph->bitmap = find_pattern(character);
            glyph->row_bytes = 1u;
            glyph->width = 5u;
            glyph->height = 7u;
            glyph->advance = 6u;
            glyph->x_offset = 0;
            glyph->y_offset = 0;
        }
        initialized = true;
    }
    return &font;
}

const gp100_bitmap_font_t *gp100_development_font_10x14(void)
{
    static gp100_bitmap_glyph_t large_glyphs[ASCII_GLYPH_COUNT];
    static uint8_t bitmaps[ASCII_GLYPH_COUNT][14u * 2u];
    static const gp100_bitmap_font_t large_font = {
        large_glyphs, ASCII_GLYPH_COUNT, 16u, 12u
    };
    static bool large_initialized;

    if (!large_initialized) {
        const gp100_bitmap_font_t *small = gp100_development_font_5x7();
        for (size_t i = 0u; i < small->glyph_count; ++i) {
            const gp100_bitmap_glyph_t *glyph = &small->glyphs[i];
            large_glyphs[i] = (gp100_bitmap_glyph_t){
                glyph->codepoint, glyph->bitmap == NULL ? NULL : bitmaps[i],
                2u, 10u, 14u, 12u, 0, 0
            };
            if (glyph->bitmap == NULL) {
                continue;
            }
            for (size_t row = 0u; row < glyph->height; ++row) {
                uint16_t doubled = 0u;
                for (unsigned column = 0u; column < glyph->width; ++column) {
                    if ((glyph->bitmap[row] & (0x80u >> column)) != 0u) {
                        doubled |= (uint16_t)(0xc000u >> (2u * column));
                    }
                }
                bitmaps[i][row * 4u] = bitmaps[i][row * 4u + 2u] =
                    (uint8_t)(doubled >> 8u);
                bitmaps[i][row * 4u + 1u] = bitmaps[i][row * 4u + 3u] =
                    (uint8_t)doubled;
            }
        }
        large_initialized = true;
    }
    return &large_font;
}
