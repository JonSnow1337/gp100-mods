bool gp100_usb_build_string_descriptor(
    uint8_t index,
    uint8_t *output,
    size_t output_capacity,
    size_t *output_length)
{
    size_t required;
    size_t input_length;
    size_t position;

    if (index >= GP100_USB_STRING_COUNT || output_length == NULL) {
        return false;
    }
    if (index == 0u) {
        required = 4u;
        *output_length = required;
        if (output == NULL || output_capacity < required) {
            return false;
        }
        output[0] = 4u;
        output[1] = 3u;
        output[2] = 9u;
        output[3] = 4u;
        return true;
    }

    input_length = strlen(strings[index]);
    required = 2u + input_length * 2u;
    *output_length = required;
    if (required > UINT8_MAX || output == NULL || output_capacity < required) {
        return false;
    }
    output[0] = (uint8_t)required;
    output[1] = 3u;
    for (position = 0u; position < input_length; ++position) {
        output[2u + position * 2u] = (uint8_t)strings[index][position];
        output[3u + position * 2u] = 0u;
    }
    return true;
}
